const fs = require("node:fs");
const path = require("node:path");

// Keep the local SQLite schema as the single source of model definitions.
// MySQL needs explicit long-text columns and bounded indexed/relation keys.
function writeMysqlSchema() {
  const source = fs.readFileSync("prisma/schema.prisma", "utf8");
  let schema = source.replace('provider = "sqlite"', 'provider = "mysql"');
  schema = schema.replace(/model\s+(\w+)\s*\{([\s\S]*?)\n\}/g, (_, model, body) => {
    const bounded = new Set();
    for (const match of body.matchAll(/(?:fields:|@@(?:index|unique|id)\()\s*\[([^\]]+)\]/g)) {
      for (const field of match[1].split(",")) bounded.add(field.trim());
    }
    const fields = body.replace(/^(\s+)(\w+)(\s+String\??)([^\n]*)$/gm, (line, indent, name, type, attributes) => {
      if (/@db\./.test(attributes)) throw new Error("Native column types belong in the generated MySQL schema only");
      const indexed = /@(?:id|unique)\b/.test(attributes) || bounded.has(name);
      const native = model === "User" && name === "email"
        ? "@db.VarChar(254)"
        : indexed || /@default\(/.test(attributes)
          ? "@db.VarChar(191)"
          : "@db.LongText";
      return `${indent}${name}${type}${attributes.trimEnd()} ${native}`;
    });
    return `model ${model} {${fields}\n}`;
  });
  schema = "// Generated by scripts/database-schema.cjs from prisma/schema.prisma.\n// Change models in the source schema and add a MySQL migration for deployment.\n" + schema;
  const file = path.join("prisma", "mysql", "schema.prisma");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== schema) fs.writeFileSync(file, schema);
  return file;
}

function schemaForUrl(url, allowMissing = false) {
  if (!url && allowMissing) return "prisma/schema.prisma";
  if (url?.startsWith("file:")) return "prisma/schema.prisma";
  if (url?.startsWith("mysql://")) {
    let parsed;
    try { parsed = new URL(url); } catch { throw new Error("DATABASE_URL is not a valid MySQL URL; URL-encode its password"); }
    if (!parsed.hostname || !parsed.username || !parsed.password || parsed.pathname.length < 2)
      throw new Error("DATABASE_URL needs a MySQL host, user, password and database name");
    return writeMysqlSchema();
  }
  throw new Error("DATABASE_URL must start with file: for local SQLite or mysql:// for MySQL");
}

module.exports = { schemaForUrl, writeMysqlSchema };
